"""One streaming pass over all.tsv: per-graph features plus the data report.

    python -m kairos_repro.data.stats

Writes results/graph_features.csv (graph_id, num_nodes, num_edges, et_<code> x26), which the
baselines use, and results/data_report.md, which answers the course's first four questions
about the data and states the class balance, with the numbers coming from this code.
"""
import csv
import sys
from collections import Counter
from pathlib import Path
from typing import Dict, Iterable, List, Optional

from kairos_repro import common as c
from kairos_repro.data.rows import iter_graph_blocks

FEATURE_FIELDS = ["graph_id", "num_nodes", "num_edges"] + ["et_" + e for e in c.EDGE_TYPES]


def new_report() -> Dict:
    return {"malformed": 0, "unknown_node_types": Counter(), "unknown_edge_types": Counter(),
            "node_type_counts": Counter(), "global_nodes": set(), "rows": 0}


def stream_graph_features(lines: Iterable[str], report: Optional[Dict] = None):
    """Yield one feature dict per graph. Fills `report` as a side effect."""
    rep = report if report is not None else new_report()

    def bad(n, line):
        rep["malformed"] += 1

    for gid, block in iter_graph_blocks(lines, on_malformed=bad):
        nodes = set()
        et = Counter()
        for r in block:
            nodes.add(r.src)
            nodes.add(r.dst)
            et[r.edge_type] += 1
            for t in (r.src_type, r.dst_type):
                rep["node_type_counts"][t] += 1
                if t not in c.NODE_TYPES:
                    rep["unknown_node_types"][t] += 1
            if r.edge_type not in c.EDGE_TYPES:
                rep["unknown_edge_types"][r.edge_type] += 1
        rep["global_nodes"].update(nodes)
        rep["rows"] += len(block)
        row = {"graph_id": gid, "num_nodes": len(nodes), "num_edges": len(block)}
        for e in c.EDGE_TYPES:
            row["et_" + e] = et.get(e, 0)
        yield row


def write_features(path: Path, rows: List[Dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=FEATURE_FIELDS)
        w.writeheader()
        w.writerows(rows)


def read_features(path: Path) -> List[Dict]:
    with open(path, newline="") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        for k in FEATURE_FIELDS:
            r[k] = int(r[k])
    return rows


def _avg(vals: List[int]) -> float:
    return sum(vals) / len(vals) if vals else 0.0


def render_report(rows: List[Dict], rep: Dict) -> str:
    by_scn: Dict[str, List[Dict]] = {k: [] for k in c.SCENARIOS}
    for r in rows:
        by_scn[c.scenario_of(r["graph_id"])].append(r)
    total_edges = sum(r["num_edges"] for r in rows)
    attack_edges = sum(r["num_edges"] for r in rows if c.label(r["graph_id"]) == 1)
    L: List[str] = ["# Data report (generated by src/kairos_repro/data/stats.py)", ""]
    L += ["## The first four questions", "",
          "**1. How big is it, and what are the columns?**  ",
          "%d edge rows in %d graphs; 6 columns: source-id, source-type, dest-id, dest-type, edge-type, graph-id. "
          "Expected: %d rows, %d graphs." % (total_edges, len(rows), c.TOTAL_EDGES, c.NUM_GRAPHS), "",
          "**2. What type is each column?**  ",
          "ids are opaque strings (kept as text), the three type columns are single-letter codes. "
          "Observed node-type codes: %s. Observed edge-type codes: %d of the %d expected."
          % (", ".join(sorted(rep["node_type_counts"])) or "none",
             sum(1 for e in c.EDGE_TYPES if any(r["et_" + e] for r in rows)), len(c.EDGE_TYPES)), "",
          "**3. What is missing or malformed?**  ",
          "%d malformed lines skipped; %d unknown node-type codes; %d unknown edge-type codes."
          % (rep["malformed"], sum(rep["unknown_node_types"].values()), sum(rep["unknown_edge_types"].values())), "",
          "**4. What does the thing we predict look like?**  ",
          "Label = 1 for graphs 300-399 (drive-by-download), else 0. All data: 500 benign / 100 attack graphs. "
          "Test split: %d benign / %d attack, so attack share is %.1f%%; guessing benign every time scores %.3f accuracy "
          "(the do-nothing baseline, `make baselines`)."
          % (len(c.TEST_BENIGN_IDS), len(c.TEST_ATTACK_IDS),
             100.0 * len(c.TEST_ATTACK_IDS) / len(c.TEST_IDS),
             len(c.TEST_BENIGN_IDS) / float(len(c.TEST_IDS))), ""]
    L += ["## Per-scenario averages vs paper Table 3", "",
          "| Scenario | Graphs | Avg nodes (ours) | Avg edges (ours) | Paper label | Paper nodes | Paper edges |",
          "|---|---|---|---|---|---|---|"]
    avg = {}
    for k, rs in by_scn.items():
        an, ae = _avg([r["num_nodes"] for r in rs]), _avg([r["num_edges"] for r in rs])
        avg[k] = (an, ae)
        pl = c.PAPER_LABEL_OF[k]
        pn, pe = c.PAPER_TABLE3[pl]
        L.append("| %s | %d | %.0f | %.0f | %s | %d | %d |" % (k, len(rs), an, ae, pl, pn, pe))
    L.append("")

    def near(a, b):
        return b != 0 and abs(a - b) / b < 0.01

    vg, dl = avg["vgame"], avg["download"]
    pv, pdl = c.PAPER_TABLE3["Video Game"], c.PAPER_TABLE3["Download"]
    if rows and near(vg[1], pdl[1]) and near(dl[1], pv[1]):
        L += ["**Finding:** our vgame averages match the paper's *Download* row and our download averages match "
              "the paper's *Video Game* row. The paper's Table 3 appears to have those two rows swapped "
              "(graph ids per the dataset README: vgame 200-299, download 400-499).", ""]
    else:
        L += ["No Video Game / Download swap detected at the 1%% level; compare the table above by hand.", ""]
    L += ["## Totals vs paper Table 2", "",
          "| Quantity | Ours | Paper |", "|---|---|---|",
          "| Edges | %d | %.1f M |" % (total_edges, c.PAPER_TABLE2["edges_millions"]),
          "| Attack edges | %d | %d |" % (attack_edges, c.PAPER_TABLE2["attack_edges"]),
          "| Attack share | %.3f%% | %.3f%% |" % (100.0 * attack_edges / total_edges if total_edges else 0.0,
                                                  c.PAPER_TABLE2["attack_pct"]),
          "| Distinct node ids | %d | %d |" % (len(rep["global_nodes"]), c.PAPER_TABLE2["nodes"]), "",
          "The reference code allocates a node-memory table for 5,045,000 nodes. The distinct count above "
          "is what a compacted table needs (see docs/decisions/ADR-0005-node-id-compaction.md).", ""]
    return "\n".join(L)


def main() -> int:
    if not c.RAW_TSV.exists():
        print("missing %s: run `make data` first" % c.RAW_TSV)
        return 1
    rep = new_report()
    with open(c.RAW_TSV, "r") as fh:
        rows = list(stream_graph_features(fh, rep))
    write_features(c.FEATURES_CSV, rows)
    c.RESULTS.mkdir(exist_ok=True)
    (c.RESULTS / "data_report.md").write_text(render_report(rows, rep))
    print("wrote", c.FEATURES_CSV, "and results/data_report.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
